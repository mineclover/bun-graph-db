import { describe, expect, test, vi } from 'vitest'
import { TableTemplateAutoGenerator } from '@/application/services/TableTemplateAutoGenerator.js'
import { Attribute } from '@/domain/entities/Attribute.js'
import { AttributeType } from '@/domain/entities/AttributeType.js'
import type { QueryTemplate } from '@/domain/entities/QueryTemplate.js'
import type { IAttributeRepository } from '@/domain/repositories/IAttributeRepository.js'
import type { IAttributeTypeRepository } from '@/domain/repositories/IAttributeTypeRepository.js'
import type { IQueryTemplateRepository } from '@/domain/repositories/IQueryTemplateRepository.js'

function emptyPage<T>(data: T[] = []) {
  return {
    data,
    nodes: data,
    totalCount: data.length,
    hasNextPage: false,
    hasPreviousPage: false,
  }
}

function createLogger() {
  return {
    info: vi.fn(() => {}),
    warn: vi.fn(() => {}),
    error: vi.fn(() => {}),
    debug: vi.fn(() => {}),
  }
}

describe('TableTemplateAutoGenerator', () => {
  test('uses resolved attribute type data when generating attribute templates', async () => {
    const now = new Date('2026-04-16T00:00:00.000Z')
    const attribute = Attribute.fromDatabase(
      'attr_active',
      'table_accounts',
      'is_active',
      'Active',
      'type_boolean',
      null,
      true,
      null,
      now,
      now,
    )
    const attributeType = AttributeType.fromDatabase(
      'type_boolean',
      'boolean_type',
      'boolean',
      null,
      null,
      null,
      null,
      null,
      null,
      now,
      now,
    )
    const generator = new TableTemplateAutoGenerator(
      {
        search: vi.fn(async () => ({ items: [], total: 0, hasNextPage: false, hasPreviousPage: false })),
        create: vi.fn(async (template) => template),
        update: vi.fn(async (_id, _updates) => {
          throw new Error('update should not be called')
        }),
      } as unknown as IQueryTemplateRepository,
      {
        findByTableId: vi.fn(async () => emptyPage([attribute])),
      } as unknown as IAttributeRepository,
      createLogger(),
      {
        findByIds: vi.fn(async () => [attributeType]),
      } as unknown as IAttributeTypeRepository,
    )

    const templates = await generator.generateTemplatesForTable('table_accounts', 'accounts')
    const setter = templates.find((template) => template.identifier === 'auto-set-accounts-is_active')

    expect(setter?.query).toContain('$isActive: Boolean!')
    expect(templates.find((template) => template.identifier === 'auto-workflow-accounts')?.query).toContain(
      '# - is_active: boolean (required)',
    )
  })

  test('marks generated table templates stale through template metadata', async () => {
    const update = vi.fn(async (_id: string, updates: { tags?: string[] }) => ({
      getTags: () => updates.tags ?? [],
    }) as unknown as QueryTemplate)
    const staleTemplate = {
      getId: () => 'template-1',
      getTags: () => ['table:table_accounts', 'auto-generated', 'attribute'],
    } as unknown as QueryTemplate
    const generator = new TableTemplateAutoGenerator(
      {
        search: vi.fn(async () => ({
          items: [staleTemplate],
          total: 1,
          hasNextPage: false,
          hasPreviousPage: false,
        })),
        update,
      } as unknown as IQueryTemplateRepository,
      {} as unknown as IAttributeRepository,
      createLogger(),
    )

    const result = await generator.markAutoGeneratedTemplatesStale('table_accounts')

    expect(result).toEqual({ marked: 1, scanned: 1 })
    expect(update).toHaveBeenCalledWith(
      'template-1',
      expect.objectContaining({
        tags: expect.arrayContaining(['schema-stale']),
      }),
    )
    const [, updates] = update.mock.calls[0]
    expect(updates.tags?.some((tag) => tag.startsWith('schema-stale-at:'))).toBe(true)
  })
})
