  private async loadFilteredRelations(
    filter: RelationAnalyticsFilterInput & { timeWindow?: StrengthAnalysisFilterInput['timeWindow'] },
  ): Promise<NodeRelation[]> {
    const [allRelations, resolvedTypes] = await Promise.all([
      filter.tableIds && filter.tableIds.length > 0
        ? this.loadRelationsForTables(filter.tableIds)
        : this.loadAllRelations(),
      filter.relationTypes && filter.relationTypes.length > 0
        ? resolveRelationTypeRefs(this.relationTypeRepository, filter.relationTypes)
        : Promise.resolve(undefined),
    ])

    if (resolvedTypes && resolvedTypes.ids.length === 0) {
      return []
    }
    const allowedTypeIds = resolvedTypes ? new Set(resolvedTypes.ids) : null
    const minWindowMs = resolveTimeWindowStartMs(filter.timeWindow)
    const startMs = filter.timeRange?.start ? Date.parse(filter.timeRange.start) : minWindowMs
    const endMs = filter.timeRange?.end ? Date.parse(filter.timeRange.end) : undefined

    return allRelations.filter((rel) => {
      if (allowedTypeIds && !allowedTypeIds.has(rel.getRelationTypeId())) return false
      if (filter.includeExternal === false) {
        if (rel.getSourceExternalId() !== 'internal' || rel.getTargetExternalId() !== 'internal') return false
      }
      if (filter.strengthRange) {
        const s = rel.getStrength()
        if (s < filter.strengthRange.min || s > filter.strengthRange.max) return false
      }
      if (filter.confidenceRange) {
        const c = rel.getConfidence()
        if (c < filter.confidenceRange.min || c > filter.confidenceRange.max) return false
      }
      if (startMs !== undefined && Number.isFinite(startMs) && rel.getCreatedAt().getTime() < startMs) return false
      if (endMs !== undefined && Number.isFinite(endMs) && rel.getCreatedAt().getTime() > endMs) return false
      return true
    })
  }

