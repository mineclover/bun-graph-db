function emptyOptimalPath() {
  return {
    path: [],
    totalDistance: 0,
    averageStrength: 0,
    averageConfidence: 0,
    pathQuality: 'UNRELIABLE' as PathQuality,
    alternativePaths: [],
  }
}

function summarizeWeightedPath(result: WeightedPathResult<IndexedEdge>, nodeMap: ReadonlyMap<string, Node>) {
  const pathNodes = result.nodeIds.flatMap((id, index) => {
    const node = nodeMap.get(id)
    if (!node) return []
    const edgeToNext = result.edges[index]
    return [
      {
        node: nodeFromEntity(node),
        relation: edgeToNext ? nodeRelationFromEntity(edgeToNext.relation) : null,
        distanceFromSource: index,
        strengthToNext: edgeToNext ? edgeToNext.strength : null,
        confidenceToNext: edgeToNext ? edgeToNext.confidence : null,
      },
    ]
  })
  const avgStrength =
    result.edges.length > 0 ? result.edges.reduce((sum, e) => sum + e.strength, 0) / result.edges.length : 0
  const avgConfidence =
    result.edges.length > 0 ? result.edges.reduce((sum, e) => sum + e.confidence, 0) / result.edges.length : 0
  const qualityScore = (avgStrength + avgConfidence) / 2
  const pathQuality: PathQuality =
    result.edges.length === 0
      ? 'EXCELLENT'
      : qualityScore >= 3.5
        ? 'EXCELLENT'
        : qualityScore >= 2.5
          ? 'GOOD'
          : qualityScore >= 1.5
            ? 'AVERAGE'
            : qualityScore >= 0.75
              ? 'POOR'
              : 'UNRELIABLE'

  return {
    pathNodes,
    totalDistance: Number(result.totalCost.toFixed(6)),
    averageStrength: avgStrength,
    averageConfidence: avgConfidence,
    pathQuality,
  }
}

function bucketStrength(
  dist: { invalid: number; autoGenerated: number; uncertain: number; confident: number; veryStrong: number },
  value: number,
) {
  if (value <= 0) dist.invalid += 1
  else if (value === 1) dist.autoGenerated += 1
  else if (value === 2) dist.uncertain += 1
  else if (value === 3) dist.confident += 1
  else dist.veryStrong += 1
}

function bucketConfidence(
  dist: { probablyWrong: number; autoGenerated: number; uncertainButValid: number; confident: number; verified: number },
  value: number,
) {
  if (value <= 0) dist.probablyWrong += 1
  else if (value === 1) dist.autoGenerated += 1
  else if (value === 2) dist.uncertainButValid += 1
  else if (value === 3) dist.confident += 1
  else dist.verified += 1
}

function addSetEdge(map: Map<string, Set<string>>, from: string, to: string) {
  let set = map.get(from)
  if (!set) {
    set = new Set()
    map.set(from, set)
  }
  set.add(to)
}

function pushMapArray<K, V>(map: Map<K, V[]>, key: K, item: V) {
  let arr = map.get(key)
  if (!arr) {
    arr = []
    map.set(key, arr)
  }
  arr.push(item)
}

function deduplicateRelations(relations: readonly NodeRelation[]): NodeRelation[] {
  const seen = new Map<string, NodeRelation>()
  for (const rel of relations) {
    seen.set(rel.getId(), rel)
  }
  return [...seen.values()]
}

function computeNodeClustering(nodeId: string, undirected: ReadonlyMap<string, Set<string>>): number {
  const neighbors = [...(undirected.get(nodeId) ?? [])].filter((id) => id !== nodeId)
  const k = neighbors.length
  if (k < 2) return 0
  let triangleEdges = 0
  for (let i = 0; i < k; i += 1) {
    const a = neighbors[i]
    if (!a) continue
    const aNeighbors = undirected.get(a)
    if (!aNeighbors) continue
    for (let j = i + 1; j < k; j += 1) {
      const b = neighbors[j]
      if (b && aNeighbors.has(b)) triangleEdges += 1
    }
  }
  return (2 * triangleEdges) / (k * (k - 1))
}

function computeAverageClusteringCoefficient(undirected: ReadonlyMap<string, Set<string>>): number {
  if (undirected.size === 0) return 0
  let sum = 0
  for (const id of undirected.keys()) {
    sum += computeNodeClustering(id, undirected)
  }
  return sum / undirected.size
}

function computeSampleAveragePathLength(
  directed: ReadonlyMap<string, Set<string>>,
  nodeIds: readonly string[],
): number {
  if (nodeIds.length < 2) return 0
  const sources = nodeIds.slice(0, MAX_SAMPLE_AVG_PATH_SOURCES)
  let totalDist = 0
  let pairs = 0
  for (const source of sources) {
    const dist = new Map<string, number>([[source, 0]])
    const queue = [source]
    while (queue.length > 0) {
      const curr = queue.shift()
      if (!curr) continue
      const d = dist.get(curr) ?? 0
      if (d >= 16) continue
      for (const next of directed.get(curr) ?? []) {
        if (!dist.has(next)) {
          dist.set(next, d + 1)
          totalDist += d + 1
          pairs += 1
          queue.push(next)
        }
      }
    }
  }
  return pairs > 0 ? totalDist / pairs : 0
}

function computeAverageDegree(undirected: ReadonlyMap<string, Set<string>>): number {
  if (undirected.size === 0) return 0
  let sum = 0
  for (const neighbors of undirected.values()) {
    sum += neighbors.size
  }
  return sum / undirected.size
}

function computeApproximateBetweenness(
  targetId: string,
  undirected: ReadonlyMap<string, Set<string>>,
): number {
  const nodes = [...undirected.keys()].slice(0, 60)
  if (nodes.length < 3) return 0
  let hits = 0
  let totalPairs = 0
  for (let i = 0; i < nodes.length; i += 1) {
    const start = nodes[i]
    if (!start || start === targetId) continue
    const dist = new Map<string, number>([[start, 0]])
    const parent = new Map<string, string>()
    const queue = [start]
    while (queue.length > 0) {
      const curr = queue.shift()
      if (!curr) continue
      const d = dist.get(curr) ?? 0
      for (const next of undirected.get(curr) ?? []) {
        if (!dist.has(next)) {
          dist.set(next, d + 1)
          parent.set(next, curr)
          queue.push(next)
        }
      }
    }
    for (let j = i + 1; j < nodes.length; j += 1) {
      const end = nodes[j]
      if (!end || end === targetId || !dist.has(end)) continue
      totalPairs += 1
      let cursor: string | undefined = parent.get(end)
      while (cursor && cursor !== start) {
        if (cursor === targetId) {
          hits += 1
          break
        }
        cursor = parent.get(cursor)
      }
    }
  }
  return totalPairs > 0 ? hits / totalPairs : 0
}

function findTriangles(undirected: ReadonlyMap<string, Set<string>>, maxCount: number): string[][] {
  const triangles: string[][] = []
  const keys = [...undirected.keys()].sort()
  for (const a of keys) {
    const aN = undirected.get(a)
    if (!aN || aN.size < 2) continue
    for (const b of aN) {
      if (b <= a) continue
      const bN = undirected.get(b)
      if (!bN) continue
      for (const c of aN) {
        if (c <= b || !bN.has(c)) continue
        triangles.push([a, b, c])
        if (triangles.length >= maxCount) return triangles
      }
    }
  }
  return triangles
}

function findLongestDirectedChain(
  nodeIds: readonly string[],
  outgoing: ReadonlyMap<string, string[]>,
  maxDepth: number,
): string[] {
  let bestChain: string[] = []
  for (const start of nodeIds.slice(0, 50)) {
    const path = [start]
    const visited = new Set([start])
    let current = start
    for (let step = 0; step < maxDepth; step += 1) {
      const next = (outgoing.get(current) ?? []).find((candidate) => !visited.has(candidate))
      if (!next) break
      visited.add(next)
      path.push(next)
      current = next
    }
    if (path.length > bestChain.length) bestChain = path
  }
  return bestChain
}

function averageConfidenceRatio(rels: readonly NodeRelation[]): number {
  if (rels.length === 0) return 0
  return rels.reduce((sum, r) => sum + r.getConfidence() / 4, 0) / rels.length
}

function averageStrengthValue(rels: readonly NodeRelation[]): number {
  if (rels.length === 0) return 0
  return rels.reduce((sum, r) => sum + r.getStrength(), 0) / rels.length
}

function resolveTimeWindowStartMs(window?: StrengthAnalysisFilterInput['timeWindow']): number | undefined {
  if (!window || window === 'ALL_TIME') return undefined
  const now = Date.now()
  if (window === 'LAST_HOUR') return now - 3_600_000
  if (window === 'LAST_DAY') return now - 86_400_000
  if (window === 'LAST_WEEK') return now - 7 * 86_400_000
  if (window === 'LAST_MONTH') return now - 30 * 86_400_000
  return undefined
}
