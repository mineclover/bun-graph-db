import type { CreateTableInput, CreateTableOutput } from '@/application/dtos/TableDto.js'
import { fromEntity as tableFromEntity } from '@/application/dtos/TableDto.js'
import type { ILogger } from '@/application/ports/ILogger.js'
import { TableTemplateAutoGenerator } from '@/application/services/TableTemplateAutoGenerator.js'
import { Table } from '@/domain/entities/Table.js'
import type { IAttributeRepository } from '@/domain/repositories/IAttributeRepository.js'
import type { IQueryTemplateRepository } from '@/domain/repositories/IQueryTemplateRepository.js'
import type { ITableRepository } from '@/domain/repositories/ITableRepository.js'
import { ConflictException, ValidationException } from '@/shared/exceptions/DomainException.js'

export class CreateTableUseCase {
  private readonly templateAutoGenerator: TableTemplateAutoGenerator

  constructor(
    private readonly tableRepository: ITableRepository,
    private readonly queryTemplateRepository: IQueryTemplateRepository,
    private readonly attributeRepository: IAttributeRepository,
    private readonly logger: ILogger,
  ) {
    this.templateAutoGenerator = new TableTemplateAutoGenerator(
      this.queryTemplateRepository,
      this.attributeRepository,
      this.logger,
    )
  }

  async execute(input: CreateTableInput): Promise<CreateTableOutput> {
    this.logger.info('Creating new table', { identifier: input.identifier })

    // Validate input
    if (!input.identifier?.trim()) {
      throw new ValidationException('Table identifier is required')
    }

    // Check if table already exists
    const existingTable = await this.tableRepository.findByIdentifier(input.identifier)
    if (existingTable) {
      throw new ConflictException(`Table with identifier '${input.identifier}' already exists`)
    }

    try {
      // Create domain entity
      const table = Table.create(input.identifier, input.description)

      // Save to repository and get the saved table with generated ID
      const savedTableResult = await this.tableRepository.save(table)

      // Ensure we have a valid table (save should always return the table for new entities)
      if (!savedTableResult) {
        throw new Error('Table save returned void unexpectedly')
      }
      const savedTable = savedTableResult

      this.logger.info('Table created successfully', {
        id: savedTable.id,
        identifier: savedTable.identifier,
      })

      // Auto-generate basic templates for the new table
      try {
        await this.templateAutoGenerator.createAutoGeneratedTemplates(savedTable.id, savedTable.identifier)
        this.logger.info('Auto-generated templates created successfully', {
          tableId: savedTable.id,
          identifier: savedTable.identifier,
        })
      } catch (error) {
        this.logger.warn('Failed to auto-generate templates, but table creation succeeded', {
          tableId: savedTable.id,
          identifier: savedTable.identifier,
          error: error instanceof Error ? error.message : String(error),
        })
        // Don't fail table creation if template generation fails
      }

      // Return DTO
      return {
        table: tableFromEntity(savedTable),
      }
    } catch (error) {
      this.logger.error('Failed to create table', {
        identifier: input.identifier,
        error: error instanceof Error ? error.message : String(error),
      })
      throw error
    }
  }
}
