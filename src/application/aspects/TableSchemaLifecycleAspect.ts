import type { ILogger } from '@/application/ports/ILogger.js'
import { TableSchemaProjectionService } from '@/application/services/TableSchemaProjectionService.js'
import { TableTemplateAutoGenerator } from '@/application/services/TableTemplateAutoGenerator.js'
import type { IAttributeRepository } from '@/domain/repositories/IAttributeRepository.js'
import type { IAttributeTypeRepository } from '@/domain/repositories/IAttributeTypeRepository.js'
import type { IQueryTemplateRepository } from '@/domain/repositories/IQueryTemplateRepository.js'
import {
  refreshMcpCacheForTableSchema,
  removeMcpCacheForTableSchema,
} from '@/presentation/mcp/factory/TableMcpServerFactory.js'

/**
 * Browser/edge-portable subset of BestEffortTabularSyncHook so TableSchemaLifecycleAspect
 * carries zero runtime dependency on node:fs.
 */
export interface TabularSyncLifecycleNotifier {
  notifyByTableId?(tableId: string): void
  notifyClearByIdentifier?(tableIdentifier: string): void
}

export interface TableSchemaLifecycleAspectDeps {
  logger: ILogger
  attributeRepository?: IAttributeRepository
  attributeTypeRepository?: IAttributeTypeRepository
  queryTemplateRepository?: IQueryTemplateRepository
  tabularSyncHook?: TabularSyncLifecycleNotifier
}

export interface TableSchemaChangeOptions {
  markTemplatesStale?: boolean
  notifyTabularSync?: boolean
}

function normalizeTableRefs(tableReferences: string | string[]): string[] {
  const rawList = Array.isArray(tableReferences) ? tableReferences : [tableReferences]
  return Array.from(new Set(rawList.map((ref) => ref?.trim()).filter((ref): ref is string => Boolean(ref))))
}

/**
 * Cross-cutting AOP aspect coordinating table-schema invalidation across:
 * 1) TableSchemaProjectionService allocation cache
 * 2) Table-scoped MCP server schema caches
 * 3) Auto-generated QueryTemplate staleness marking
 * 4) Best-effort tabular sync notifications
 */
export class TableSchemaLifecycleAspect {
  constructor(private readonly deps: TableSchemaLifecycleAspectDeps) {}

  async onTableSchemaChanged(
    tableReferences: string | string[],
    operation: string,
    options: TableSchemaChangeOptions = {},
  ): Promise<void> {
    const refs = normalizeTableRefs(tableReferences)
    if (refs.length === 0) return

    for (const ref of refs) {
      TableSchemaProjectionService.clearCache(ref)
    }

    try {
      const cacheResult = await refreshMcpCacheForTableSchema(refs)
      if (cacheResult.refreshed.length > 0) {
        this.deps.logger.info('MCP table schema cache refreshed', {
          operation,
          refreshed: cacheResult.refreshed,
        })
      }
      if (cacheResult.failed.length > 0) {
        this.deps.logger.warn('MCP table schema cache refresh failed', {
          operation,
          failed: cacheResult.failed,
        })
      }
    } catch (error) {
      this.deps.logger.warn('MCP table schema cache refresh threw unexpectedly', {
        operation,
        error: error instanceof Error ? error.message : String(error),
      })
    }

    if (
      options.markTemplatesStale !== false &&
      this.deps.queryTemplateRepository &&
      this.deps.attributeRepository
    ) {
      const generator = new TableTemplateAutoGenerator(
        this.deps.queryTemplateRepository,
        this.deps.attributeRepository,
        this.deps.logger,
        this.deps.attributeTypeRepository,
      )

      for (const ref of refs) {
        try {
          await generator.markAutoGeneratedTemplatesStale(ref)
        } catch (error) {
          this.deps.logger.warn('Generated template stale marking failed', {
            operation,
            tableId: ref,
            error: error instanceof Error ? error.message : String(error),
          })
        }
      }
    }

    if (options.notifyTabularSync !== false && this.deps.tabularSyncHook?.notifyByTableId) {
      for (const ref of refs) {
        try {
          this.deps.tabularSyncHook.notifyByTableId(ref)
        } catch (error) {
          this.deps.logger.warn('Tabular sync table notification failed', {
            operation,
            tableId: ref,
            error: error instanceof Error ? error.message : String(error),
          })
        }
      }
    }
  }

  onTableDeleted(
    tableId: string,
    tableIdentifier: string | undefined,
    operation: string,
  ): void {
    const refs = normalizeTableRefs([
      tableId,
      ...(tableIdentifier ? [tableIdentifier] : []),
    ])
    if (refs.length === 0) return

    for (const ref of refs) {
      TableSchemaProjectionService.clearCache(ref)
    }

    try {
      const cacheResult = removeMcpCacheForTableSchema(refs)
      if (cacheResult.removed.length > 0) {
        this.deps.logger.info('Removed table-scoped MCP schema cache after table deletion', {
          operation,
          removed: cacheResult.removed,
        })
      }
    } catch (error) {
      this.deps.logger.warn('Failed to remove table-scoped MCP schema cache', {
        operation,
        error: error instanceof Error ? error.message : String(error),
      })
    }

    if (tableIdentifier && this.deps.tabularSyncHook?.notifyClearByIdentifier) {
      try {
        this.deps.tabularSyncHook.notifyClearByIdentifier(tableIdentifier)
      } catch (error) {
        this.deps.logger.warn('Tabular sync clear notification failed', {
          operation,
          tableIdentifier,
          error: error instanceof Error ? error.message : String(error),
        })
      }
    }
  }
}
