import type { ILogger } from '@/application/ports/ILogger.js'
import { TableTemplateAutoGenerator } from '@/application/services/TableTemplateAutoGenerator.js'
import type { AttributeDto } from '@/application/dtos/AttributeDto.js'
import type { CreateAttributeTypeUseCase } from '@/application/use-cases/attribute-types/CreateAttributeType.js'
import type { CreateAttributeUseCase } from '@/application/use-cases/attributes/CreateAttribute.js'
import type {
  GraphQLContext,
  GraphQLParent,
  MutationCreateAttributeArgs,
  MutationCreateAttributeTypeArgs,
  MutationDeleteAttributeArgs,
  MutationDeleteAttributeTypeArgs,
  MutationUpdateAttributeArgs,
  MutationUpdateAttributeTypeArgs,
} from '@/core/types/GraphQLTypes.js'
import type { IAttributeRepository } from '@/domain/repositories/IAttributeRepository.js'
import type { IAttributeTypeRepository } from '@/domain/repositories/IAttributeTypeRepository.js'
import type { IQueryTemplateRepository } from '@/domain/repositories/IQueryTemplateRepository.js'
import type { BestEffortTabularSyncHook } from '@/application/services/BestEffortTabularSyncHook.js'
import { refreshMcpCacheForTableSchema } from '@/presentation/mcp/factory/TableMcpServerFactory.js'
import { BaseResolver } from '../base/BaseResolver.js'

export class AttributeMutations extends BaseResolver {
  protected logger: ILogger

  constructor(
    private readonly createAttributeTypeUseCase: CreateAttributeTypeUseCase,
    private readonly createAttributeUseCase: CreateAttributeUseCase,
    private readonly attributeTypeRepository: IAttributeTypeRepository,
    private readonly attributeRepository: IAttributeRepository,
    logger: ILogger,
    private readonly tabularSyncHook?: BestEffortTabularSyncHook,
    private readonly queryTemplateRepository?: IQueryTemplateRepository,
  ) {
    super()
    this.logger = logger
  }

  private async refreshTableSchemaCache(
    tableReferences: string | string[],
    operation: string,
  ): Promise<void> {
    const cacheResult = await refreshMcpCacheForTableSchema(tableReferences)
    if (cacheResult.refreshed.length > 0) {
      this.logger.info('MCP table schema cache refreshed', {
        operation,
        refreshed: cacheResult.refreshed,
      })
    }
    if (cacheResult.failed.length > 0) {
      this.logger.warn('MCP table schema cache refresh failed', {
        operation,
        failed: cacheResult.failed,
      })
    }
  }

  private async getTableIdsUsingAttributeType(
    attributeTypeId: string,
  ): Promise<string[]> {
    const tableIds = new Set<string>()
    const limit = 1000
    let offset = 0

    while (true) {
      const attributesResult =
        await this.attributeRepository.findByAttributeTypeId(attributeTypeId, {
          limit,
          offset,
        })
      const attributes = attributesResult.data ?? attributesResult.nodes ?? []
      for (const attribute of attributes) {
        tableIds.add(attribute.getTableId())
      }

      if (!attributesResult.hasMore && !attributesResult.hasNextPage) {
        break
      }
      offset += limit
    }

    return Array.from(tableIds)
  }

  private async markGeneratedTemplatesStale(
    tableReferences: string | string[],
    operation: string,
  ): Promise<void> {
    if (!this.queryTemplateRepository) return

    const generator = new TableTemplateAutoGenerator(
      this.queryTemplateRepository,
      this.attributeRepository,
      this.logger,
      this.attributeTypeRepository,
    )

    const tableIds = Array.isArray(tableReferences) ? tableReferences : [tableReferences]
    for (const tableId of [...new Set(tableIds)]) {
      try {
        await generator.markAutoGeneratedTemplatesStale(tableId)
      } catch (error) {
        this.logger.warn('Generated template stale marking failed', {
          operation,
          tableId,
          error: error instanceof Error ? error.message : String(error),
        })
      }
    }
  }

  async createAttributeType(
    _: GraphQLParent,
    args: MutationCreateAttributeTypeArgs,
    _context?: GraphQLContext,
  ) {
    this.validateArgs(
      args,
      [
        BaseResolver.validationRules.required(
          'input',
          'Create attribute type input',
        ),
        BaseResolver.validationRules.required('input.identifier', 'Identifier'),
        BaseResolver.validationRules.required('input.name', 'Name'),
        BaseResolver.validationRules.required('input.dataType', 'Data type'),
        BaseResolver.validationRules.nonEmpty('input.identifier', 'Identifier'),
        BaseResolver.validationRules.nonEmpty('input.name', 'Name'),
      ],
      'createAttributeType',
    )

    return this.handleMutation(
      async () => {
        const result = await this.createAttributeTypeUseCase.execute({
          identifier: args.input.identifier,
          jsonType: args.input.dataType,
          description: args.input.description ?? undefined,
          validationSchema:
            args.input.constraints && typeof args.input.constraints === 'object'
              ? (args.input.constraints as Record<string, unknown>)
              : undefined,
          defaultValue: args.input.defaultValue ?? undefined,
        })

        // Map the DTO to GraphQL format
        if (result?.attributeType) {
          return {
            ...result.attributeType,
            dataType: result.attributeType.jsonType,
            name: args.input.name,
            constraints: result.attributeType.validationSchema,
          }
        }
        return null
      },
      'createAttributeType',
      { input: args.input },
    ).then((mutationResult) => ({
      success: mutationResult.success,
      attributeType: mutationResult.data,
      errors: mutationResult.errors || [],
    }))
  }

  async updateAttributeType(
    _: GraphQLParent,
    args: MutationUpdateAttributeTypeArgs,
    _context?: GraphQLContext,
  ) {
    this.validateArgs(
      args,
      [
        BaseResolver.validationRules.required('id', 'Attribute type ID'),
        BaseResolver.validationRules.required(
          'input',
          'Update attribute type input',
        ),
        BaseResolver.validationRules.nonEmpty('id', 'Attribute type ID'),
      ],
      'updateAttributeType',
    )

    return this.handleMutation(
      async () => {
        const existingAttributeType =
          await this.attributeTypeRepository.findById(args.id)
        if (!existingAttributeType) {
          throw new Error('Attribute type not found')
        }

        const affectedTableIds = await this.getTableIdsUsingAttributeType(
          args.id,
        )
        const updatedAttributeType = await this.attributeTypeRepository.update(
          args.id,
          {
            identifier: args.input.name || undefined,
            description: args.input.description || undefined,
            jsonType: undefined, // Not available in input
            format: undefined, // Not available in input
            validationSchema:
              args.input.constraints &&
              typeof args.input.constraints === 'object'
                ? (args.input.constraints as Record<string, unknown>)
                : undefined,
            defaultValue: args.input.defaultValue || undefined,
          },
        )

        await this.refreshTableSchemaCache(
          affectedTableIds,
          'updateAttributeType',
        )
        await this.markGeneratedTemplatesStale(
          affectedTableIds,
          'updateAttributeType',
        )

        return updatedAttributeType
      },
      'updateAttributeType',
      { id: args.id, input: args.input },
    ).then((mutationResult) => ({
      success: mutationResult.success,
      attributeType: mutationResult.data,
      errors: mutationResult.errors || [],
    }))
  }

  async deleteAttributeType(
    _: GraphQLParent,
    args: MutationDeleteAttributeTypeArgs,
    _context?: GraphQLContext,
  ) {
    this.validateArgs(
      args,
      [
        BaseResolver.validationRules.required('id', 'Attribute type ID'),
        BaseResolver.validationRules.nonEmpty('id', 'Attribute type ID'),
      ],
      'deleteAttributeType',
    )

    return this.handleMutation(
      async () => {
        const existingAttributeType =
          await this.attributeTypeRepository.findById(args.id)
        if (!existingAttributeType) {
          throw new Error('Attribute type not found')
        }

        const affectedTableIds = await this.getTableIdsUsingAttributeType(
          args.id,
        )
        await this.attributeTypeRepository.delete(args.id)
        await this.refreshTableSchemaCache(
          affectedTableIds,
          'deleteAttributeType',
        )
        await this.markGeneratedTemplatesStale(
          affectedTableIds,
          'deleteAttributeType',
        )
        return null
      },
      'deleteAttributeType',
      { id: args.id },
    ).then((mutationResult) => ({
      success: mutationResult.success,
      errors: mutationResult.errors || [],
    }))
  }

  async createAttribute(
    _: GraphQLParent,
    args: MutationCreateAttributeArgs,
    _context?: GraphQLContext,
  ) {
    this.validateArgs(
      args,
      [
        BaseResolver.validationRules.required(
          'input',
          'Create attribute input',
        ),
        BaseResolver.validationRules.required('input.identifier', 'Identifier'),
        BaseResolver.validationRules.required(
          'input.attributeTypeId',
          'Attribute type ID',
        ),
        BaseResolver.validationRules.required('input.tableId', 'Table ID'),
        BaseResolver.validationRules.nonEmpty('input.identifier', 'Identifier'),
        BaseResolver.validationRules.nonEmpty(
          'input.attributeTypeId',
          'Attribute type ID',
        ),
        BaseResolver.validationRules.nonEmpty('input.tableId', 'Table ID'),
      ],
      'createAttribute',
    )

    return this.handleMutation(
      async () => {
        const result = await this.createAttributeUseCase.execute({
          identifier: args.input.identifier,
          description: args.input.description || undefined,
          attributeTypeId: args.input.attributeTypeId,
          tableId: args.input.tableId,
        })

        this.tabularSyncHook?.notifyByTableId(args.input.tableId)
        await this.refreshTableSchemaCache(
          result.attribute.tableId,
          'createAttribute',
        )

        return result
      },
      'createAttribute',
      { input: args.input },
    ).then((mutationResult) => ({
      success: mutationResult.success,
      attribute: mutationResult.data?.attribute,
      errors: mutationResult.errors || [],
    }))
  }

  async updateAttribute(
    _: GraphQLParent,
    args: MutationUpdateAttributeArgs,
    _context?: GraphQLContext,
  ) {
    this.validateArgs(
      args,
      [
        BaseResolver.validationRules.required('id', 'Attribute ID'),
        BaseResolver.validationRules.required(
          'input',
          'Update attribute input',
        ),
        BaseResolver.validationRules.nonEmpty('id', 'Attribute ID'),
      ],
      'updateAttribute',
    )

    return this.handleMutation(
      async () => {
        const existingAttribute = await this.attributeRepository.findById(
          args.id,
        )
        if (!existingAttribute) {
          throw new Error('Attribute not found')
        }

        const updatedAttribute = await this.attributeRepository.update(
          args.id,
          {
            identifier: args.input.name || undefined,
            description: args.input.description || undefined,
            isRequired: undefined, // Not available in input
            defaultValue: undefined, // Not available in input
          },
        )

        this.tabularSyncHook?.notifyByTableId(existingAttribute.getTableId())
        await this.refreshTableSchemaCache(
          existingAttribute.getTableId(),
          'updateAttribute',
        )
        await this.markGeneratedTemplatesStale(
          existingAttribute.getTableId(),
          'updateAttribute',
        )

        return updatedAttribute
      },
      'updateAttribute',
      { id: args.id, input: args.input },
    ).then((mutationResult) => ({
      success: mutationResult.success,
      attribute: mutationResult.data,
      errors: mutationResult.errors || [],
    }))
  }

  async deleteAttribute(
    _: GraphQLParent,
    args: MutationDeleteAttributeArgs,
    _context?: GraphQLContext,
  ) {
    this.validateArgs(
      args,
      [
        BaseResolver.validationRules.required('id', 'Attribute ID'),
        BaseResolver.validationRules.nonEmpty('id', 'Attribute ID'),
      ],
      'deleteAttribute',
    )

    return this.handleMutation(
      async () => {
        const existingAttribute = await this.attributeRepository.findById(
          args.id,
        )
        if (!existingAttribute) {
          throw new Error('Attribute not found')
        }

        await this.attributeRepository.delete(args.id)
        this.tabularSyncHook?.notifyByTableId(existingAttribute.getTableId())
        await this.refreshTableSchemaCache(
          existingAttribute.getTableId(),
          'deleteAttribute',
        )
        await this.markGeneratedTemplatesStale(
          existingAttribute.getTableId(),
          'deleteAttribute',
        )
        return null
      },
      'deleteAttribute',
      { id: args.id },
    ).then((mutationResult) => ({
      success: mutationResult.success,
      errors: mutationResult.errors || [],
    }))
  }

  async batchCreateAttributes(
    _: GraphQLParent,
    args: {
      attributes: Array<{
        tableId: string
        identifier: string
        name?: string
        attributeTypeId: string
        description?: string
      }>
    },
  ) {
    const results: Array<{ attribute: AttributeDto | null; errors: string[] }> =
      []
    let totalCreated = 0
    let totalFailed = 0

    for (const attributeInput of args.attributes || []) {
      try {
        const result = await this.createAttributeUseCase.execute({
          tableId: attributeInput.tableId,
          identifier: attributeInput.identifier,
          name: attributeInput.name,
          attributeTypeId: attributeInput.attributeTypeId,
          description: attributeInput.description,
        })
        totalCreated++
        results.push({
          attribute: result.attribute,
          errors: [],
        })
      } catch (error) {
        totalFailed++
        results.push({
          attribute: null,
          errors: [error instanceof Error ? error.message : 'Unknown error'],
        })
      }
    }

    const createdTableIds = results
      .map((result) => result.attribute?.tableId)
      .filter((tableId): tableId is string => typeof tableId === 'string')

    if (createdTableIds.length > 0) {
      await this.refreshTableSchemaCache(
        createdTableIds,
        'batchCreateAttributes',
      )
      await this.markGeneratedTemplatesStale(
        createdTableIds,
        'batchCreateAttributes',
      )
    }

    return {
      success: totalFailed === 0,
      results,
      totalCreated,
      totalFailed,
    }
  }
}
