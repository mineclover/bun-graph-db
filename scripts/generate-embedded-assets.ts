import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'

interface EmbeddedDocument {
  path: string
  sdl: string
}

const repoRoot = resolve(import.meta.dirname, '..')
const schemaSqlPath = resolve(repoRoot, 'scripts/database/schema.sql')
const graphqlSchemaRoot = resolve(repoRoot, 'src/presentation/graphql/schema')
const outputFilePath = resolve(repoRoot, 'src/generated/embedded-assets.ts')

function collectGraphqlFiles(dir: string): string[] {
  const entries = readdirSync(dir, { withFileTypes: true })
  const collected: string[] = []

  for (const entry of entries) {
    const fullPath = resolve(dir, entry.name)
    if (entry.isDirectory()) {
      collected.push(...collectGraphqlFiles(fullPath))
    } else if (entry.isFile() && entry.name.endsWith('.graphql')) {
      collected.push(fullPath)
    }
  }

  return collected.sort((a, b) => a.localeCompare(b))
}

function generateEmbeddedAssetsSource(): string {
  const initialSchemaSql = readFileSync(schemaSqlPath, 'utf-8')
  const schemaFiles = collectGraphqlFiles(graphqlSchemaRoot)
  const documents: EmbeddedDocument[] = schemaFiles.map((filePath) => ({
    path: relative(repoRoot, filePath).replace(/\\/g, '/'),
    sdl: readFileSync(filePath, 'utf-8'),
  }))

  const hasher = createHash('sha256')
  hasher.update(initialSchemaSql)
  for (const doc of documents) {
    hasher.update('\n---GRAPHQL---\n')
    hasher.update(doc.path)
    hasher.update('\n')
    hasher.update(doc.sdl)
  }
  const versionHash = hasher.digest('hex')

  const docsLiteral = documents
    .map(
      (doc) =>
        `  {\n    path: ${JSON.stringify(doc.path)},\n    sdl: ${JSON.stringify(doc.sdl)},\n  },`,
    )
    .join('\n')

  return [
    '// Auto-generated by scripts/generate-embedded-assets.ts. Do not edit manually.',
    '',
    'export interface EmbeddedGraphqlSdlDocument {',
    '  readonly path: string',
    '  readonly sdl: string',
    '}',
    '',
    `export const EMBEDDED_ASSETS_VERSION_HASH = ${JSON.stringify(versionHash)}`,
    '',
    `export const EMBEDDED_INITIAL_SCHEMA_SQL = ${JSON.stringify(initialSchemaSql)}`,
    '',
    'export const EMBEDDED_GRAPHQL_SDL_DOCUMENTS: readonly EmbeddedGraphqlSdlDocument[] = [',
    docsLiteral,
    ']',
    '',
  ].join('\n')
}

const isCheckMode = process.argv.includes('--check')
const generatedSource = generateEmbeddedAssetsSource()

if (isCheckMode) {
  if (!existsSync(outputFilePath)) {
    console.error(`Missing generated embedded assets file: ${outputFilePath}`)
    console.error('Run: pnpm run generate:embedded')
    process.exit(1)
  }
  const existingSource = readFileSync(outputFilePath, 'utf-8')
  if (existingSource !== generatedSource) {
    console.error('Generated embedded assets are out of date.')
    console.error('Run: pnpm run generate:embedded')
    process.exit(1)
  }
  console.log('Embedded assets are up to date.')
} else {
  mkdirSync(dirname(outputFilePath), { recursive: true })
  writeFileSync(outputFilePath, generatedSource, 'utf-8')
  console.log(`Generated embedded assets at ${relative(repoRoot, outputFilePath)}`)
}
