import { readFile } from 'node:fs/promises'
import {
  createGoogleSheetsPipeBuilderConfig,
  createGoogleSpreadsheet,
  createGoogleToolsHttpSpreadsheet,
  createTabularDestinationGateways,
  ExcelSchemaProjector,
  type ExcelProjectableAttribute,
  type ExcelProjectableNode,
  TabularSyncPlanner,
  TabularSyncService,
  TabularSyncTargetRegistry,
} from '@/infrastructure/excel/index.js'

async function main() {
  const pipeBuilderWorkspacePath =
    process.env.PIPE_BUILDER_WORKSPACE_PATH ||
    '/Users/junwoobang/workflow/pipe-builder'
  const transport =
    (process.env.TABULAR_TARGET_TRANSPORT as
      | 'pipe-builder-table-adapter'
      | 'google-tools-http'
      | 'google-tools-submodule'
      | undefined) || 'pipe-builder-table-adapter'
  const googleToolsBaseUrl =
    process.env.GOOGLE_TOOLS_BASE_URL || 'http://localhost:5678'
  const serviceAccountKeyFile =
    process.env.GOOGLE_CREDENTIALS_FILE ||
    process.env.GOOGLE_SERVICE_ACCOUNT_KEY_FILE
  const oauthTokenFile = process.env.GOOGLE_OAUTH_TOKEN_FILE
  const authMode = oauthTokenFile ? 'oauth' : 'service-account'

  if (
    transport !== 'google-tools-http' &&
    !serviceAccountKeyFile &&
    !oauthTokenFile
  ) {
    throw new Error(
      'Provide GOOGLE_CREDENTIALS_FILE/GOOGLE_SERVICE_ACCOUNT_KEY_FILE or GOOGLE_OAUTH_TOKEN_FILE.',
    )
  }
  const spreadsheetUrl = process.env.GOOGLE_SHEETS_SPREADSHEET_URL
  let spreadsheetId = process.env.GOOGLE_SHEETS_SPREADSHEET_ID
  if (!spreadsheetId) {
    try {
      const created =
        transport === 'google-tools-http'
          ? await createGoogleToolsHttpSpreadsheet({
              baseUrl: googleToolsBaseUrl,
              title: `bun-graph-db-smoke-${Date.now()}`,
            })
          : await createGoogleSpreadsheet({
              workspacePath: pipeBuilderWorkspacePath,
              authMode,
              serviceAccountKeyFile,
              oauthTokenFile,
              title: `bun-graph-db-smoke-${Date.now()}`,
            })
      spreadsheetId = created.spreadsheetId
      console.log(
        JSON.stringify(
          {
            createdSpreadsheet: created,
          },
          null,
          2,
        ),
      )
    } catch (error) {
      const details = serviceAccountKeyFile
        ? (JSON.parse(await readFile(serviceAccountKeyFile, 'utf8')) as {
            client_email?: string
          })
        : {}

      const message = error instanceof Error ? error.message : String(error)
      throw new Error(
        [
          message,
          'Automatic spreadsheet creation failed.',
          transport === 'google-tools-http'
            ? `Ensure the authenticated google-tools server at ${googleToolsBaseUrl} can create spreadsheets.`
            : null,
          authMode === 'oauth'
            ? 'Set GOOGLE_SHEETS_SPREADSHEET_ID to an existing spreadsheet accessible to the authenticated Google account.'
            : 'Set GOOGLE_SHEETS_SPREADSHEET_ID to an existing spreadsheet shared with the service account.',
          details.client_email
            ? `Share the spreadsheet with: ${details.client_email}`
            : null,
        ]
          .filter(Boolean)
          .join(' '),
      )
    }
  }
  const tableIdentifier = process.env.TABULAR_TABLE_IDENTIFIER || 'users'
  const sheetName = process.env.GOOGLE_SHEETS_SHEET_NAME || tableIdentifier

  const config = createGoogleSheetsPipeBuilderConfig({
    spreadsheetId,
    spreadsheetUrl,
    serviceAccountKeyFile,
    oauthTokenFile,
    authMode,
    transport,
    googleToolsBaseUrl,
    tableIdentifier,
    sheetName,
    pipeBuilderWorkspacePath,
  })

  const registry = new TabularSyncTargetRegistry(config)
  const planner = new TabularSyncPlanner(
    registry,
    new ExcelSchemaProjector(),
  )
  const syncService = new TabularSyncService(
    registry,
    planner,
    createTabularDestinationGateways(),
  )

  const attributes: ExcelProjectableAttribute[] = [
    { identifier: 'email', dataType: 'email', required: true, searchable: true },
    { identifier: 'department', dataType: 'text', searchable: true },
  ]

  const nodes: ExcelProjectableNode[] = [
    {
      id: 'smoke-node-1',
      title: 'Smoke User',
      content: 'Google Sheets smoke sync row',
      description: 'Generated by smoke-google-sheets-tabular-sync.ts',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      attributes: {
        email: 'smoke@example.com',
        department: 'platform',
      },
    },
  ]

  const preview = await syncService.preview({
    tableIdentifier,
    description: 'Smoke sync table',
    attributes,
    nodes,
  })

  if (!preview) {
    throw new Error('No sync route resolved from config')
  }

  console.log(
    JSON.stringify(
      {
        selection: preview.selection,
        spreadsheetId,
        diffSummary: {
          added: preview.diff.added,
          removed: preview.diff.removed,
          changed: preview.diff.changed,
          unchanged: preview.diff.unchanged,
        },
      },
      null,
      2,
    ),
  )

  const result = await syncService.sync({
    tableIdentifier,
    description: 'Smoke sync table',
    attributes,
    nodes,
  })

  console.log(JSON.stringify(result, null, 2))
}

main().catch((error) => {
  console.error(
    JSON.stringify(
      {
        success: false,
        error: error instanceof Error ? error.message : String(error),
      },
      null,
      2,
    ),
  )
  process.exitCode = 1
})
